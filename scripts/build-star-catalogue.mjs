// Builds src/data/stars.ts from the Yale Bright Star Catalogue (BSC5, CDS V/50).
// Not part of the build: run it by hand, commit its output.
//
//   curl -o catalog.gz https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz
//   gunzip catalog.gz            (keep the file outside the repo)
//   node scripts/build-star-catalogue.mjs path/to/catalog [maxMag=4.5]
//
// Fixed-width columns used (1-based, per the V/50 ReadMe): RAh 76-77, RAm 78-79,
// RAs 80-83, DE sign 84, DEd 85-86, DEm 87-88, DEs 89-90 (all J2000), Vmag 103-107.
import { readFileSync, writeFileSync } from "node:fs";

const [src, maxArg] = process.argv.slice(2);
if (!src) {
  console.error("usage: node scripts/build-star-catalogue.mjs <catalog file> [maxMag]");
  process.exit(1);
}
const maxMag = maxArg ? Number(maxArg) : 4.5;
const round = (n) => Math.round(n * 1000) / 1000;
const field = (line, from, to) => line.slice(from - 1, to).trim();

const stars = [];
for (const line of readFileSync(src, "utf8").split(/\r?\n/)) {
  if (line.length < 107) continue;
  const rah = field(line, 76, 77);
  const vmag = field(line, 103, 107);
  if (!rah || !vmag) continue; // novae/non-stellar entries lack coordinates or magnitude
  const mag = Number(vmag);
  if (!Number.isFinite(mag) || mag > maxMag) continue;
  const ra = Number(rah) + Number(field(line, 78, 79)) / 60 + Number(field(line, 80, 83)) / 3600;
  const sign = field(line, 84, 84) === "-" ? -1 : 1;
  const dec = sign * (Number(field(line, 85, 86)) + Number(field(line, 87, 88)) / 60 + Number(field(line, 89, 90)) / 3600);
  if (![ra, dec].every(Number.isFinite)) continue;
  stars.push({ ra: round(ra), dec: round(dec), mag });
}
stars.sort((a, b) => a.mag - b.mag);

const rows = stars.map((s) => `  { ra: ${s.ra}, dec: ${s.dec}, mag: ${s.mag} },`).join("\n");
writeFileSync(
  new URL("../src/data/stars.ts", import.meta.url),
  `// Generated by scripts/build-star-catalogue.mjs. Do not edit by hand.
// Source: Yale Bright Star Catalogue, 5th revised ed. (Hoffleit & Warren), CDS V/50,
// https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz. Stars with V magnitude <= ${maxMag}.
// ra in hours (J2000), dec in degrees (J2000), mag = visual magnitude. Sorted brightest first.
export type CatalogueStar = { ra: number; dec: number; mag: number };

export const STARS: readonly CatalogueStar[] = [
${rows}
];
`,
);
console.log(`wrote ${stars.length} stars (mag <= ${maxMag})`);
